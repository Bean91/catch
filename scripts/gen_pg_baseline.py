"""Regenerates migrations/versions/0001_baseline.sql from the SQLModel metadata.

The baseline is a frozen snapshot of the schema as of the Alembic baseline — never regenerate it once a
database has been migrated; later changes are new Alembic revisions (`alembic revision --autogenerate`).
tests/test_pg_migrations.py fails if `alembic upgrade head` and the metadata ever disagree."""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import AddConstraint, CreateIndex, CreateTable, sort_tables_and_constraints
from sqlmodel import SQLModel

import catch.core.models  # noqa: F401

OUT = Path(__file__).resolve().parent.parent / "migrations" / "versions" / "0001_baseline.sql"


def render() -> str:
    dialect = postgresql.dialect()
    parts = ["-- Generated by scripts/gen_pg_baseline.py. Runs with search_path = catch.\n"]
    # activities / canonical_activities / pieces reference each other; the foreign keys that close the cycle
    # come back with table=None and are added after everything exists.
    for table, fkcs in sort_tables_and_constraints(SQLModel.metadata.tables.values()):
        if table is None:
            for fk in sorted(fkcs, key=lambda c: (c.parent.name, c.name or "")):
                parts.append(str(AddConstraint(fk).compile(dialect=dialect)).strip() + ";\n")
            continue
        parts.append(str(CreateTable(table, include_foreign_key_constraints=fkcs).compile(dialect=dialect)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\n")
    return "\n".join(parts)


if __name__ == "__main__":
    if OUT.exists() and "--force" not in sys.argv:
        sys.exit(f"{OUT} exists; the baseline is frozen. Pass --force only before it has been applied anywhere.")
    OUT.write_text(render())
    print(f"wrote {OUT}")
